    private void Lista() {
        
        try
        {
            Connection con=(Connection)DriverManager.getConnection("jdbc:mysql://127.0.0.1/banco", "root", "");
            String sql;
            sql = "select * from cadastro";
            PreparedStatement banco = (PreparedStatement)con.prepareStatement(sql);
            banco.execute();
            ResultSet resultado = banco.executeQuery(sql);
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setNumRows(0);
            while(resultado.next())
            {
                model.addRow(new Object[]
                {
                    resultado.getString("id"),
                    resultado.getString("nome"),
                    resultado.getString("endereco"),
                    resultado.getString("bairro"),
                    resultado.getString("cidade"),
                    resultado.getString("uf"),
                    resultado.getString("cep"),
                    resultado.getString("cnpj"),
                    resultado.getString("ie"),
                    resultado.getString("fone"),
                    resultado.getString("celular"),
                    resultado.getString("fax"),
                    resultado.getString("contato"),
                    resultado.getString("email"),
                    resultado.getString("web"),
                    resultado.getString("observacao")
                });
            }
            
            banco.close();
            con.close();       
        }
        catch(SQLException ex)
        {
            System.out.println("O erro foi: " + ex);
        }
    }

