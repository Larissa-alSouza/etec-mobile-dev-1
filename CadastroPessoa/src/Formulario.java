    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        
        int response = JOptionPane.showConfirmDialog(null, "Deseja alterar os dados?", "Confirmação",
            JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
    
        if (response == JOptionPane.YES_OPTION) {
            try {
                Connection con=(Connection)DriverManager.getConnection("jdbc:mysql://127.0.0.1/banco", "root", "");
                Statement stmt=(Statement)con.createStatement();

                // Atualiza o registro com os novos dados
                String update = "UPDATE cadastro SET "
                + "nome = '" + jtfNome.getText() + "', "
                + "endereco = '" + jtfEndereco.getText() + "', "
                + "bairro = '" + jtfBairro.getText() + "', "
                + "cidade = '" + jtfCidade.getText() + "', "
                + "uf = '" + jtfUF.getText() + "', "
                + "cep = '" + jtfCEP.getText() + "', "
                + "cnpj_cpf = '" + jtfCNPJ.getText() + "', "
                + "ie = '" + jtfIE.getText() + "', "
                + "fone = '" + jtfFone.getText() + "', "
                + "celular = '" + jtfCelular.getText() + "', "
                + "fax = '" + jtfFax.getText() + "', "
                + "contato = '" + jtfContato.getText() + "', "
                + "email = '" + jtfEmail.getText() + "', "
                + "web = '" + jtfWEB.getText() + "', "
                + "observacao = '" + jtfObservacao.getText() + "' "
                + "WHERE id = " + jtfID.getText();

                stmt.executeUpdate(update);
                JOptionPane.showMessageDialog(null, "Dados alterados com sucesso!");
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(null, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
            // Após atualizar, atualizar a tabela ou limpar os campos
            this.Lista(); // Se necessário, recarregar os dados da tabela
        }
    }//GEN-LAST:event_btnAlterarActionPerformed

